_SORTED = sorted((p for p in PAIRS if len(p[0]) >= 3), key=lambda p: -len(p[0]))
_CYR = re.compile("[А-Яа-яЁё]")


def tr(s):
    if LANG == "ru" or not s or not isinstance(s, str) or not _CYR.search(s):
        return s
    if s in _EXACT:
        return _EXACT[s]
    for a, b in _SORTED:
        if a in s:
            s = s.replace(a, b)
    return s
